function bound(p, end) {
    switch (p.kind) {
        case 'Range': return p[end];
        case 'Choice': return end === 'min' ? Math.min(...p.options) : Math.max(...p.options);
        case 'Transition': return { start: p[end], end: p[end], curve: p.def.curve };
        case 'Text': return p.def;
    }
}

function digest(samples) {
    const values = [];
    for (let start = 0; start < samples.length; start += BLOCK) {
        const end = Math.min(samples.length, start + BLOCK);
        let peak = 0, sum = 0;
        for (let i = start; i < end; i++) {
            const x = samples[i];
            peak = Math.max(peak, Math.abs(x));
            sum += x * x;
        }
        values.push(peak, Math.sqrt(sum / (end - start)), samples[start]);
    }
    return values.map(x => String(Number(x.toPrecision(9)))).join(' ');
}

function kRaw(text) {
    if (text.includes('$') || text.includes('"""')) throw new Error(`no raw string literal fits: ${text}`);
    return `"""${text}"""`;
}

function kChunks(text) {
    const chunks = [];
    for (let i = 0; i < text.length; i += CHUNK) chunks.push(text.slice(i, i + CHUNK));
    return chunks.map(c => `            ${kString(c)},`).join('\n');
}

function goldenFile(name, cases) {
    const body = cases.map(c => `    Golden(
        name = ${kString(c.name)},
        sound = ${kRaw(c.json)},
        frames = ${c.frames},
        digest = listOf(
${kChunks(c.digest)}
        ).joinToString(""),
    ),`).join('\n');
    return `${header}package fromcrackpot.kintsugi.bfxr.goldens

internal val ${name.toUpperCase()}_GOLDENS: List<Golden> = listOf(
${body}
)
`;
}

function mulberryFile(rng) {
    const rows = MULBERRY_SEEDS.map(seed => {
        const next = rng(seed);
        const draws = Array.from({ length: MULBERRY_DRAWS }, () => kDouble(next()));
        return `    ${kDouble(seed)} to doubleArrayOf(\n        ${draws.join(',\n        ')},\n    ),`;
    }).join('\n');
    return `${header}package fromcrackpot.kintsugi.bfxr.goldens

internal val MULBERRY32_GOLDENS: List<Pair<Double, DoubleArray>> = listOf(
${rows}
)
`;
}

function akwfFile(akwf) {
    const tables = AKWF_TABLES.map(name => {
        const table = akwf[name];
        if (!Array.isArray(table) || table.length !== 256 || !table.every(Number.isInteger)) {
            throw new Error(`AKWF.${name} is no longer 256 integers`);
        }
        const rows = [];
        for (let i = 0; i < table.length; i += 16) rows.push(`    ${table.slice(i, i + 16).join(', ')},`);
        return `internal val AKWF_${name.toUpperCase()}: IntArray = intArrayOf(\n${rows.join('\n')}\n)`;
    }).join('\n\n');
    return `${header}package fromcrackpot.kintsugi.bfxr.dsp\n\n${tables}\n`;
}

