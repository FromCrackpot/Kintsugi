const sha256 = data => createHash('sha256').update(data).digest('hex');

async function fetchSource() {
    const cached = join(moduleDir, `build/bfxr2/bfxrlib-${COMMIT.slice(0, 7)}.js`);
    try {
        const data = await readFile(cached);
        if (sha256(data) === SHA256) return data.toString('utf8');
    } catch {}
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error(`fetching ${SOURCE_URL}: HTTP ${response.status}`);
    const data = Buffer.from(await response.arrayBuffer());
    const actual = sha256(data);
    if (actual !== SHA256) throw new Error(`bfxrlib.js hash mismatch: expected ${SHA256}, got ${actual}`);
    await mkdir(dirname(cached), { recursive: true });
    await writeFile(cached, data);
    return data.toString('utf8');
}

function load(source) {
    const marker = 'global.bfxr = {';
    if (source.split(marker).length !== 2) throw new Error('bfxrlib.js no longer exports through a single global.bfxr');
    const context = vm.createContext({ console });
    const exposed = `global.__synths = BFXR_SYNTHS; global.__rng = SoundDSP.rng; global.__akwf = AKWF; ${marker}`;
    vm.runInContext(source.replace(marker, exposed), context, { filename: 'bfxrlib.js' });
    return { bfxr: context.bfxr, synths: context.__synths, rng: context.__rng, akwf: context.__akwf };
}

function schemaOf(name, Synth) {
    const synth = new Synth();
    const params = synth.param_info.map(info => {
        const param = synth.get_param_normalized(info);
        switch (param.type) {
            case 'RANGE':
                return { kind: 'Range', name: param.name, min: param.min_value, max: param.max_value, def: param.default_value };
            case 'BUTTONSELECT':
                return { kind: 'Choice', name: param.name, options: info.values.map(v => v[2]), def: param.default_value };
            case 'KNOB_TRANSITION':
                return {
                    kind: 'Transition', name: param.name, min: param.min_value, max: param.max_value,
                    curves: info.curves || [info.default_tween], def: param.default_value,
                };
            case 'TEXT':
                return { kind: 'Text', name: param.name, maxLength: info.max_length, def: param.default_value };
            default:
                throw new Error(`${name}.${param.name}: unknown parameter type ${param.type}`);
        }
    });
    return { name, version: synth.version, params };
}

const kDouble = x => {
    if (!Number.isFinite(x)) throw new Error(`not a finite number: ${x}`);
    const s = String(x);
    return /[.eE]/.test(s) ? s : `${s}.0`;
};
const kString = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"';

function kParam(p) {
    const name = kString(p.name);
    switch (p.kind) {
        case 'Range':
            return `Range(${name}, ${kDouble(p.min)}, ${kDouble(p.max)}, BfxrValue.Number(${kDouble(p.def)}))`;
        case 'Choice':
            return `Choice(${name}, listOf(${p.options.join(', ')}), BfxrValue.Number(${kDouble(p.def)}))`;
        case 'Transition':
            return `Transition(${name}, ${kDouble(p.min)}, ${kDouble(p.max)}, listOf(${p.curves.map(kString).join(', ')}), ` +
                `BfxrValue.Transition(${kDouble(p.def.start)}, ${kDouble(p.def.end)}, ${kString(p.def.curve)}))`;
        case 'Text':
            return `Text(${name}, ${p.maxLength}, BfxrValue.Text(${kString(p.def)}))`;
    }
}

function synthEnum(schemas) {
    const entries = schemas.map(s => {
        const summary = SUMMARIES[s.name];
        if (!summary) throw new Error(`no KDoc summary for synth ${s.name}; add one to SUMMARIES`);
        const params = s.params.map(p => `            ${kParam(p)},`).join('\n');
        return `    /** ${summary} */\n    ${s.name.toUpperCase()}(\n        ${kString(s.name)},\n        ${kString(s.version)},\n` +
            `        listOf(\n${params}\n        ),\n    ),`;
    }).join('\n\n');
    return `${header}package fromcrackpot.kintsugi.bfxr

import fromcrackpot.kintsugi.bfxr.BfxrParam.Choice
import fromcrackpot.kintsugi.bfxr.BfxrParam.Range
import fromcrackpot.kintsugi.bfxr.BfxrParam.Text
import fromcrackpot.kintsugi.bfxr.BfxrParam.Transition

/**
 * The synths of the \`.bfxr\` format, each with the version and the parameters a file must match.
 *
 * - Pinned to one bfxr2 release: a file saved by a newer bfxr2 with another version is rejected, not guessed at.
 *
 * @param id The name a file gives in \`synth_type\`, case-sensitive.
 * @param version The version a file must give for this synth.
 * @param params The parameters, in bfxr2's order.
 */
public enum class BfxrSynth(
    public val id: String,
    public val version: String,
    public val params: List<BfxrParam>,
) {
${entries}
}
`;
}

function soundWith(schema, pick) {
    const params = {};
    for (const p of schema.params) params[p.name] = pick(p);
    return { synth_type: schema.name, version: schema.version, params, renderSeed: 0.5 };
}

const extremes = schema => [
    ['defaults', soundWith(schema, p => p.def)],
    ['minimum', soundWith(schema, p => p.name === 'masterVolume' ? p.def : bound(p, 'min'))],
    ['maximum', soundWith(schema, p => bound(p, 'max'))],
];

const sweeps = schema => (SWEEPS[schema.name] ?? []).flatMap(name => {
    const param = schema.params.find(p => p.name === name);
    if (param?.kind !== 'Choice') throw new Error(`${schema.name}.${name}: a sweep needs a choice parameter`);
    return param.options.map(option => [`${name}=${option}`, soundWith(schema, p => p.name === name ? option : p.def)]);
});

function randoms(schema, rng, bfxr) {
    const next = rng(RANDOM_SEED);
    const cases = [];
    while (cases.length < (RANDOM_CASES[schema.name] ?? 0)) {
        const sound = soundWith(schema, p => {
            if (p.name === 'masterVolume') return p.def;
            switch (p.kind) {
                case 'Range': return p.min + next() * (p.max - p.min);
                case 'Choice': return p.options[Math.floor(next() * p.options.length)];
                case 'Transition': {
                    const start = p.min + next() * (p.max - p.min);
                    const end = p.min + next() * (p.max - p.min);
                    return { start, end, curve: p.curves[Math.floor(next() * p.curves.length)] };
                }
                default: throw new Error(`${schema.name}.${p.name}: no random ${p.kind}`);
            }
        });
        sound.renderSeed = next();
        if (bfxr.render(sound).length > 0) cases.push([`random-${cases.length + 1}`, sound]);
    }
    return cases;
}

